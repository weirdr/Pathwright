#!/usr/bin/env python3
"""Generate addon/Pathwright_Guide/QuestItems.lua: for each quest, the item it hands out when it
is taken (the game data's source item).

    python3 addon/tools/quest_items.py [--db data/forever.sqlite] [--out addon/Pathwright_Guide/QuestItems.lua]

The toolstrip offers that item as a button while a step of the quest shows, when the character
carries it and it can be used (Toolstrip.lua): the game itself names a quest's item to use for
some quests only. The same for every player, whatever guide they use.
"""
import argparse
import os
import sqlite3
import subprocess
import tempfile


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="data/forever.sqlite")
    ap.add_argument("--out", default="addon/Pathwright_Guide/QuestItems.lua")
    args = ap.parse_args()
    path, tmp = args.db if os.path.exists(args.db) else args.db + ".zst", None
    if path.endswith(".zst"):
        handle = tempfile.NamedTemporaryFile(suffix=".sqlite", delete=False)
        handle.close()
        subprocess.run(["zstd", "-d", "-f", "-q", path, "-o", handle.name], check=True)
        path = tmp = handle.name
    db = sqlite3.connect(path)
    rows = db.execute(
        """select id, source_item_id from m_quest
           where source_item_id is not null and source_item_id > 0 and status in ('available', 'incomplete')
           order by id"""
    ).fetchall()
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("-- Generated by addon/tools/quest_items.py from the game database: do not edit.\n")
        f.write("-- quest -> the item it hands out when taken (see Toolstrip.lua).\n")
        f.write("Pathwright.QuestItems = {\n")
        for i in range(0, len(rows), 8):
            f.write("    " + " ".join("[%d]=%d," % row for row in rows[i : i + 8]) + "\n")
        f.write("}\n")
    print("%s: %d quests" % (args.out, len(rows)))
    if tmp:
        os.unlink(tmp)


if __name__ == "__main__":
    main()
